function preset(
  id: ThemeId,
  name: string,
  mode: 'dark' | 'light',
  base: string[],
  syntax: string[],
  ansi = vscodeAnsi,
): ThemePreset {
  const [background, surface, raised, border, text, muted, accent, selected] = base;
  const light = mode === 'light';
  const values: Record<string, string> = {
    background,
    editor: background,
    surface,
    raised,
    border,
    separator: border,
    text,
    muted,
    accent,
    accentText: text,
    hover: raised,
    selected,
    warning: light ? '#795e00' : '#e5c07b',
    warningBackground: light ? '#fff1c1' : '#49391f',
    error: light ? '#b42332' : '#ff8b98',
    errorBackground: light ? '#ffe1e4' : '#562b32',
    insert: light ? '#daf2df' : '#193d2a',
    delete: light ? '#ffdddd' : '#4b242b',
    insertGutter: light ? '#b6e3c1' : '#245237',
    deleteGutter: light ? '#f5bec4' : '#603039',
    overlay: '#0008',
    highlight: light ? '#00000008' : '#ffffff06',
    subtleBorder: light ? '#00000025' : '#ffffff25',
    accentWash: accent + '66',
    white: text,
  };
  const ui = Object.fromEntries(
    Object.keys(originalUi).map((key) => [
      key,
      id === 'original' ? originalUi[key] : values[key.replace(/\d+$/, '')],
    ]),
  );
  return Object.freeze({
    id,
    name,
    mode,
    ui: Object.freeze(ui),
    syntax: Object.freeze(
      Object.fromEntries(
        ['keyword', 'string', 'number', 'comment', 'function', 'type', 'property', 'invalid'].map(
          (key, i) => [key, syntax[i]],
        ),
      ),
    ) as SyntaxColors,
    terminal: Object.freeze({
      ...Object.fromEntries(ansiKeys.map((key, i) => [key, ansi[i]])),
      background,
      foreground: text,
      cursor: accent,
      cursorAccent: background,
      selectionBackground: id === 'original' ? '#355369' : selected,
      selectionForeground: id === 'original' ? '#1e1e1e' : text,
    }) as Required<ITheme>,
  });
}
